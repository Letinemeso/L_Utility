#pragma once


#define PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    private: _TYPE m_##_NAME = _INITIALIZATION;

#define PRIVATE_FIELD_GETTER(_TYPE, _NAME) \
    public: inline _TYPE get_##_NAME() const { return m_##_NAME; }

#define PRIVATE_FIELD_GETTER_R(_TYPE, _NAME) \
    public: inline const _TYPE& get_##_NAME() const { return m_##_NAME; }

#define PRIVATE_FIELD_SETTER(_TYPE, _NAME) \
    public: inline void set_##_NAME( _TYPE _value ) { m_##_NAME = _value; }

#define PRIVATE_FIELD_SETTER_R(_TYPE, _NAME) \
    public: inline void set_##_NAME( const _TYPE& _value ) { m_##_NAME = _value; }

#define PRIVATE_FIELD_SETTER_P(_TYPE, _NAME) \
    public: inline void set_##_NAME( _TYPE* _value ) { delete m_##_NAME; m_##_NAME = _value; }

#define PRIVATE_FIELD_SETTER_CP(_TYPE, _NAME) \
    public: inline void set_##_NAME( const _TYPE* _value ) { m_##_NAME = _value; }


#define PRIVATE_FIELD_G(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_GETTER(_TYPE, _NAME)

#define PRIVATE_FIELD_GR(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_GETTER_R(_TYPE, _NAME)


#define PRIVATE_FIELD_S(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_SETTER(_TYPE, _NAME)

#define PRIVATE_FIELD_SR(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_SETTER_R(_TYPE, _NAME)

#define PRIVATE_FIELD_SP(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_SETTER_P(_TYPE, _NAME)

#define PRIVATE_FIELD_CSP(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_SETTER_CP(_TYPE, _NAME)


#define PRIVATE_FIELD_G_S(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_GETTER(_TYPE, _NAME) \
    PRIVATE_FIELD_SETTER(_TYPE, _NAME)

#define PRIVATE_FIELD_GR_S(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_GETTER_R(_TYPE, _NAME) \
    PRIVATE_FIELD_SETTER(_TYPE, _NAME)

#define PRIVATE_FIELD_G_SR(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_GETTER(_TYPE, _NAME) \
    PRIVATE_FIELD_SETTER_R(_TYPE, _NAME)

#define PRIVATE_FIELD_GR_SR(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD(_TYPE, _NAME, _INITIALIZATION) \
    PRIVATE_FIELD_GETTER_R(_TYPE, _NAME) \
    PRIVATE_FIELD_SETTER_R(_TYPE, _NAME)